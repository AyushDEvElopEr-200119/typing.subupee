export const REGIONAL_IDS = Object.keys(PACKS) as RegionalId[];

const drills: Record<string, string[]> = {};

export const regionalLessons: Lesson[] = REGIONAL_IDS.flatMap((id) => {
  const item = PACKS[id];
  const home = rowDrill(item.script, "home");
  const top = rowDrill(item.script, "top");
  drills[`${id}-k-1`] = home.lines;
  drills[`${id}-1-1`] = top.lines;
  return pack(id, [
    { grade: "k", title: "Home row", focus: home.focus, assist: true, text: home.lines[0] },
    { grade: "1", title: "Top row", focus: top.focus, assist: true, text: top.lines[0] },
    { grade: "3", title: "Short words", focus: "words", assist: true, text: item.words },
    { grade: "5", title: "Sentences", focus: "sentences", assist: true, text: item.sentences },
    { grade: "9", title: "A paragraph", focus: "paragraph", text: item.paragraph },
    { grade: "adult", title: "A note", focus: "work", text: item.note },
  ]);
});

